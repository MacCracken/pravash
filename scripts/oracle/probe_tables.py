#!/usr/bin/env python3
"""Compile every generated Cyrius value and compare its bits with the golden rows (M0 step 6).

    python3 -I -B scripts/oracle/probe_tables.py .

The generator writes `src/constants.cyr` from the oracle and pins every value in
`tests/golden/constants.tsv`. This checks the step in between: that the Cyrius compiler reads each
generated literal or bit pattern back as exactly the oracle's value. For every constants row it
derives the Cyrius name (the generator's rule, `t_constants::cyr_name`), writes a probe program
that includes `src/constants.cyr` and prints each value's bits, builds it with `cyrius build`, runs
it, and compares. An `f32` global is compared after widening (`f32_to`), as the row stores it.

The probe compiles with the project's `[deps]`, from the repo root. Exit status 1 on any mismatch,
on a row with no generated name, or on a generated name with no row. Adapted in spirit from
tanmatra's and kimiya's probe_tables.py.
"""

import re
import subprocess
import sys
from pathlib import Path


def upper_snake(camel):
    out = ""
    for k, c in enumerate(camel):
        if c.isupper() and k > 0:
            out += "_"
        out += c.upper()
    return out


def cyr_name(path):
    """`common::FluidMaterial::WATER.density` → `PV_FLUID_MATERIAL_WATER_DENSITY`;
    `f64::MAX` → `PV_F64_MAX`; `f64::consts::PI` → `PV_F64_PI`."""
    if path.startswith(("f64::", "f32::")):
        ty, rest = path.split("::", 1)
        return f"PV_{ty.upper()}_{rest.split('::')[-1]}"
    head, _, field = path.partition(".")
    parts = head.split("::")
    name = f"PV_{upper_snake(parts[-2])}_{parts[-1]}"
    return f"{name}_{field.upper()}" if field else name


def unpct(s):
    return re.sub(r"%([0-9A-F]{2})", lambda m: chr(int(m.group(1), 16)), s)


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    rows = {}
    for line in (root / "tests/golden/constants.tsv").read_text().splitlines()[5:]:
        func, cls, ins, outs, _ = line.split("\t")
        rows[cyr_name(unpct(ins[2:]))] = int(outs[2:], 16)

    generated = (root / "src/constants.cyr").read_text()
    kinds = {}
    for m in re.finditer(r"^(const|var) (PV_\w+)(?:: (f64|f32))? = ", generated, re.M):
        kinds[m.group(2)] = m.group(3) or "f64"
    fails = []
    for name in sorted(set(rows) - set(kinds)):
        fails.append(f"{name}: a golden row with no generated value")
    for name in sorted(set(kinds) - set(rows)):
        fails.append(f"{name}: generated with no golden row")

    body = []
    for name in sorted(set(rows) & set(kinds)):
        conv = f"f32_to({name})" if kinds[name] == "f32" else name
        body.append(f'    put("{name}\\t"); var v_{name}: f64 = {conv}; fmt_hex0x(v_{name}); println("");')
    probe = "\n".join(
        [
            "# Generated by scripts/oracle/probe_tables.py; not part of the library.",
            'include "src/constants.cyr"',
            "",
            "fn put(s: cstring): i64 {",
            "    print(s, strlen(s));",
            "    return 0;",
            "}",
            "",
            "fn main(): i64 {",
            "    alloc_init();",
            *body,
            "    return 0;",
            "}",
            "",
            "var rc = main();",
            "sys_exit_group(rc);",
            "",
        ]
    )
    build = root / "build"
    build.mkdir(exist_ok=True)
    src = build / "probe_tables.cyr"
    src.write_text(probe)
    out = subprocess.run(
        ["cyrius", "build", str(src.relative_to(root)), "build/probe_tables"],
        cwd=root, capture_output=True, text=True,
    )
    diag = [l for l in (out.stdout + out.stderr).splitlines() if re.search(r"\b(error|warning)\b", l)]
    if out.returncode != 0 or diag:
        print("\n".join(diag) or out.stdout + out.stderr)
        print("FAIL the probe did not build cleanly")
        return 1
    ran = subprocess.run([str(build / "probe_tables")], cwd=root, capture_output=True, text=True)
    got = {}
    for line in ran.stdout.splitlines():
        name, bits = line.split("\t")
        got[name] = int(bits, 16)
    for name in sorted(set(rows) & set(kinds)):
        if got.get(name) != rows[name]:
            g = got.get(name)
            fails.append(f"{name}: compiled to {g:#018x}, the golden row is {rows[name]:#018x}" if g is not None
                         else f"{name}: not printed by the probe")
    for f in fails:
        print("FAIL", f)
    print(f"{len(got)} generated values compiled and compared, {len(fails)} failures")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
