//! Cyrius source emission for the generated modules (port plan §4 step 6). Adapted from impetus's
//! `scripts/oracle/src/cyr.rs` (which took it from kimiya's and tanmatra's).
//!
//! Rules the output must keep (probed on 6.7.18: impetus, kimiya, tanmatra, and pravash's step 6):
//! - **Hex is never used in a `const`**, where it is an integer and `CONST * x` then does integer
//!   arithmetic. A float constant is a `const` with a decimal literal, which is an f64.
//! - **There is no exponent notation**, so a decimal literal is written out positionally. Rust's
//!   `Display` for f64 is exactly that: the shortest round-trip digits, never an exponent. The
//!   Cyrius lexer rounds a literal correctly, so the bits come back.
//! - **A value with no literal** (±∞, NaN, or one whose positional form is unwieldy, like
//!   `f64::MAX`) is a typed `f64` global holding the bit pattern: a hex word ≥ 2^52 in an `f64` slot
//!   is the legal boxed-float idiom, with no warning.
//! - **Every global gets the `PV_` prefix.** A bundle is concatenated into its consumers, so names
//!   share one namespace.

use std::fmt::Write as _;

/// The `///` doc block directly above the first line of `src` that starts with `item` (after
/// leading whitespace; attributes in between are skipped), as `# ` comment lines. Only comments
/// are read from the Rust source; values always come from the oracle's API.
pub fn doc_comment(src: &str, item: &str) -> Result<String, String> {
    let lines: Vec<&str> = src.lines().collect();
    let at = lines
        .iter()
        .position(|l| l.trim_start().starts_with(item))
        .ok_or_else(|| format!("no `{item}` in the Rust source"))?;
    let mut docs = Vec::new();
    let mut k = at;
    while k > 0 {
        k -= 1;
        let l = lines[k].trim_start();
        if l.starts_with("#[") {
            continue;
        }
        match l.strip_prefix("///") {
            Some(rest) => docs.push(rest.strip_prefix(' ').unwrap_or(rest).to_string()),
            None => break,
        }
    }
    docs.reverse();
    let mut out = String::new();
    for d in docs {
        let _ = writeln!(out, "{}", comment_line(d.trim_end()));
    }
    Ok(out)
}

/// `line` as a `#` comment, with no trailing space when it is empty (lint-clean).
pub fn comment_line(line: &str) -> String {
    if line.is_empty() {
        "#".to_string()
    } else {
        format!("# {line}")
    }
}

/// A finite f64 as a Cyrius decimal literal: Rust's `Display` digits (shortest round-trip,
/// positional), with `.0` added to an integer so the lexer reads a float. Refuses ±∞, NaN and
/// values too long to write positionally, which go in a bit-pattern global instead.
pub fn f64_literal(x: f64) -> Result<String, String> {
    if !x.is_finite() {
        return Err(format!(
            "{x:?} has no Cyrius literal; emit it as a bit-pattern global"
        ));
    }
    let mut s = format!("{x}");
    if !s.contains('.') {
        s.push_str(".0");
    }
    if s.len() > 64 {
        return Err(format!(
            "{x:?} is {} characters positionally; emit it as a bit-pattern global",
            s.len()
        ));
    }
    // The lexer must give back exactly x: check the round trip here, as the Cyrius side will.
    match s.parse::<f64>() {
        Ok(y) if y.to_bits() == x.to_bits() => Ok(s),
        _ => Err(format!("{s} does not round-trip to {x:?}")),
    }
}

/// The generated-file header: title, provenance, regenerate command, then each note as a comment
/// paragraph.
pub fn header(title: &str, provenance: &str, notes: &[&str]) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "# pravash — {title}");
    out.push_str("#\n");
    let _ = writeln!(
        out,
        "# GENERATED by scripts/oracle from {provenance}. Do not edit."
    );
    out.push_str(
        "# Regenerate: cargo run --release --locked --manifest-path scripts/oracle/Cargo.toml\n",
    );
    for n in notes {
        out.push_str("#\n");
        for line in n.lines() {
            let _ = writeln!(out, "{}", comment_line(line));
        }
    }
    out.push('\n');
    out
}
