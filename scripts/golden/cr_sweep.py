#!/usr/bin/env python3
"""A random sweep of the correctly rounded primitives against MPFR, on inputs the golden corpus doesn't hold.

    python3 -I -B scripts/golden/cr_sweep.py . [--seed N] [--count N]

The corpus pins exp, ln, log10, sin, cos, hypot, pow and atan2 (`src/mathx.cyr`'s `_pv_*` wrappers over
`src/crmath.cyr` and `src/crlog.cyr`, ADR 0004) on its own grids. This draws about 26 × count more inputs per run:
- uniform bit patterns, which hold the subnormals, both zeros, the infinities and NaN;
- each function's hard regions: exp across its whole range; ln and log10 across every exponent and at 1 ± 2^-k;
  log10 at exact powers of ten; sin and cos to 1e308 and at the doubles nearest k·π/2; hypot at wide exponent
  gaps; pow near 1 with large exponents, at negative bases with integer exponents, at exact integer powers and at
  the ties; atan2 in every quadrant.

It writes them to build/cr_sweep/in.bin, builds and runs build/cr_sweep/sweep.tcyr (it includes tests/lib.cyr, so it
runs from the repo root), and compares every result with MPFR's correctly rounded value (scripts/golden/mpfr_ref.py),
bit for bit (any NaN matches any NaN). Exit status 1 on any difference. It needs libmpfr.so.6, like validate.py, so
it runs locally. 2.0.1's run: 209,062 inputs, 0 differences.
"""
import importlib.util
import math
import random
import struct
import subprocess
import sys
from pathlib import Path

FN = ["exp", "log", "log10", "sin", "cos", "hypot", "pow", "atan2"]

HARNESS = r'''# Generated by scripts/golden/cr_sweep.py: the correctly rounded wrappers on build/cr_sweep/in.bin's records
# (fn, x, y), each result's bits to build/cr_sweep/out.bin.
include "tests/lib.cyr"

fn main(): i64 {
    alloc_init();
    var len = 0;
    var buf = file_read_whole("build/cr_sweep/in.bin", &len);
    if (buf == 0) { println("cr_sweep: no input"); return 1; }
    var n = len / 24;
    var out = alloc(n * 8);
    for (var i = 0; i < n; i = i + 1) {
        var p = buf + i * 24;
        var k = load64(p);
        var x = load64(p + 8);
        var y = load64(p + 16);
        var r: f64 = 0.0;
        if (k == 0) { r = _pv_exp(x); }
        elif (k == 1) { r = _pv_ln(x); }
        elif (k == 2) { r = _pv_log10(x); }
        elif (k == 3) { r = _pv_sin(x); }
        elif (k == 4) { r = _pv_cos(x); }
        elif (k == 5) { r = _pv_hypot(x, y); }
        elif (k == 6) { r = _pv_powf(x, y); }
        elif (k == 7) { r = _pv_atan2(x, y); }
        store64(out + i * 8, _pv_bits(r));
    }
    if (file_write_all("build/cr_sweep/out.bin", out, n * 8) != n * 8) { println("cr_sweep: write failed"); return 1; }
    return 0;
}

var exit_code = main();
if (exit_code > 0) { exit_code = 1; }
sys_exit_group(exit_code);
'''


def fb(b):
    return struct.unpack("<d", struct.pack("<Q", b & (2**64 - 1)))[0]


def bf(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def inputs(seed, count):
    rng = random.Random(seed)

    def ub():
        return fb(rng.getrandbits(64))

    def lu(lo, hi, neg=True):
        e = rng.uniform(lo, hi)
        v = 2.0 ** e if e > -1074 else 5e-324
        if e < 1023:
            v *= rng.uniform(1, 2) / 2
        return -v if neg and rng.random() < 0.5 else v

    spec = [0.0, -0.0, math.inf, -math.inf, math.nan, 5e-324, -5e-324, 2.2250738585072014e-308,
            1.7976931348623157e308, -1.7976931348623157e308, 1.0, -1.0, 0.5, 2.0, 0.1, 10.0, math.pi, -math.pi]
    recs = []

    def add(k, x, y=0.0):
        recs.append((k, bf(x), bf(y)))

    for k in range(8):
        for x in spec:
            for y in (spec if k >= 5 else [0.0]):
                add(k, x, y)
    for _ in range(count // 2):
        for k in range(5):
            add(k, ub())
        for k in (5, 6, 7):
            add(k, ub(), ub())
    for _ in range(count):
        add(0, rng.uniform(-746, 710))
        add(0, lu(-60, -1))
        add(1, lu(-1074, 1024, False))
        add(2, lu(-1074, 1024, False))
        d = 2.0 ** -rng.uniform(1, 52) * rng.choice((1, -1))
        add(1, 1 + d)
        add(2, 1 + d)
        add(2, 10.0 ** rng.randint(-300, 300))
        for k in (3, 4):
            add(k, rng.uniform(-100, 100))
            add(k, lu(-30, 1024))
            base = rng.randint(1, 10**6) * math.pi / 2
            add(k, math.nextafter(base, math.inf) if rng.random() < .5 else base)
        add(5, lu(-1074, 1024), lu(-1074, 1024))
        a = lu(-500, 500)
        add(5, a, a * lu(-60, 60))
        add(6, lu(-20, 20, False), rng.uniform(-100, 100))
        add(6, 1 + 2.0 ** -rng.uniform(1, 52) * rng.choice((1, -1)), rng.uniform(-1e6, 1e6))
        add(6, -lu(-10, 10, False), float(rng.randint(-60, 60)))
        add(6, float(rng.randint(2, 30)), float(rng.randint(-40, 40)))
        add(6, lu(-1074, 1024, False), rng.choice((0.5, -0.5, 1 / 3, 2.5, 3.0)))
        add(7, lu(-1074, 1024), lu(-1074, 1024))
        add(7, rng.uniform(-10, 10), rng.uniform(-10, 10))
    return recs


def main():
    root = Path(sys.argv[1] if len(sys.argv) > 1 and not sys.argv[1].startswith("--") else ".").resolve()
    args = sys.argv[1:]
    seed = int(args[args.index("--seed") + 1]) if "--seed" in args else 0x2001
    count = int(args[args.index("--count") + 1]) if "--count" in args else 8000
    spec = importlib.util.spec_from_file_location("mpfr_ref", Path(__file__).resolve().parent / "mpfr_ref.py")
    mpfr = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mpfr)

    work = root / "build" / "cr_sweep"
    work.mkdir(parents=True, exist_ok=True)
    recs = inputs(seed, count)
    with open(work / "in.bin", "wb") as f:
        for r in recs:
            f.write(struct.pack("<QQQ", *r))
    (work / "sweep.tcyr").write_text(HARNESS, encoding="utf-8")
    run = subprocess.run(["cyrius", "test", "build/cr_sweep/sweep.tcyr"], cwd=root, capture_output=True, text=True)
    if run.returncode != 0:
        print(run.stdout[-2000:] + run.stderr[-2000:])
        print("cr_sweep: the harness failed")
        return 1
    out = (work / "out.bin").read_bytes()
    if len(out) != len(recs) * 8:
        print("cr_sweep: the harness wrote", len(out) // 8, "results for", len(recs), "inputs")
        return 1
    count_by = [0] * 8
    bad = {}
    for i, (k, xb, yb) in enumerate(recs):
        x, y = fb(xb), fb(yb)
        got = fb(struct.unpack_from("<Q", out, i * 8)[0])
        want = mpfr.cr2(FN[k], x, y) if k >= 5 else mpfr.cr(FN[k], x)
        count_by[k] += 1
        if math.isnan(want) and math.isnan(got):
            continue
        if bf(want) != bf(got):
            bad.setdefault(FN[k], []).append((x, y, got, want))
    total_bad = 0
    for k, name in enumerate(FN):
        b = bad.get(name, [])
        total_bad += len(b)
        print(f"{name:6s} {count_by[k]:7d} inputs, {len(b)} differ from MPFR {mpfr.VERSION}")
        for x, y, g, w in b[:5]:
            print(f"    x={x!r} y={y!r} got={g!r} mpfr={w!r}")
    print(f"{len(recs)} inputs, {total_bad} differences (seed {seed:#x})")
    return 1 if total_bad else 0


if __name__ == "__main__":
    sys.exit(main())
